/*
 * EdTechRAG search embed - a search box and a result page for any website.
 *
 * This file must stay ASCII-only: static .js is served without a charset, so a
 * classic <script src> inherits the encoding of the host page. Write non-ASCII
 * text as \uXXXX escapes.
 * Check with: LC_ALL=C grep -n '[^ -~\t]' edtechrag-search.js   (must print nothing)
 *
 * Two modes on one script, chosen with data-mode:
 *
 *   box      an input plus a button. Submitting navigates to data-results-url
 *            with ?q=... - the same thing a search field in a header does.
 *   results  reads ?q= from the address, shows the input, the result list, and
 *            above it the optional AI overview.
 *
 * The results appear WITHOUT consent; the AI overview only after it. That split is
 * the point of the feature and the reason there are two endpoints behind it.
 */
(function () {
	'use strict';

	var P = 'at-ed-tech-edtechrag-src-';

	/* -- Consent, mirroring block_chatbot/edtechrag.js -- */
	var USERTERMS_DEFAULT_MONTHS = 12;
	var USERTERMS_MIN_MONTHS = 1;
	var USERTERMS_MAX_MONTHS = 60;
	// Fixed 30-day months, matching src/lib/ragContext.ts. Calendar math is
	// timezone/DST dependent and would make client and server disagree at the
	// expiry boundary.
	var MONTH_MS = 30 * 24 * 60 * 60 * 1000;

	var TEXT = {
		en: {
			label: 'Search',
			placeholder: 'Search ...',
			submit: 'Search',
			searching: 'Searching ...',
			resultsFor: 'Results for',
			noResults: 'Nothing found. Try other words.',
			resultCount: function (n) {
				return n === 1 ? '1 result' : n + ' results';
			},
			queriesLabel: 'Searched for:',
			errorPrefix: 'Error:',
			overviewHeading: 'AI overview',
			overviewIntro:
				'A language model can summarise these results for you. Your search is sent to the model for that.',
			overviewAccept: 'Show summary',
			overviewGenerating: 'Writing summary ...',
			overviewNote: 'Generated by a language model - please check against the sources.',
			termsLinkLabel: 'Terms of use',
			menu: 'More options',
			revoke: 'Withdraw consent',
			revokeQuestion:
				'Withdraw your consent? The AI overview will be locked again; the search keeps working.',
			cancel: 'Cancel',
			noscript: 'The search needs JavaScript.'
		},
		de: {
			label: 'Suche',
			placeholder: 'Suchen ...',
			submit: 'Suchen',
			searching: 'Suche l\u00e4uft ...',
			resultsFor: 'Ergebnisse f\u00fcr',
			noResults: 'Nichts gefunden. Versuchen Sie es mit anderen Worten.',
			resultCount: function (n) {
				return n === 1 ? '1 Ergebnis' : n + ' Ergebnisse';
			},
			queriesLabel: 'Gesucht wurde nach:',
			errorPrefix: 'Fehler:',
			overviewHeading: 'KI-Zusammenfassung',
			overviewIntro:
				'Ein Sprachmodell kann diese Ergebnisse f\u00fcr Sie zusammenfassen. Dazu wird Ihre Suchanfrage an das Modell \u00fcbermittelt.',
			overviewAccept: 'Zusammenfassung anzeigen',
			overviewGenerating: 'Zusammenfassung wird geschrieben ...',
			overviewNote:
				'Von einem Sprachmodell erzeugt - bitte an den Quellen gegenpr\u00fcfen.',
			termsLinkLabel: 'Nutzungsbedingungen',
			menu: 'Weitere Optionen',
			revoke: 'Zustimmung widerrufen',
			revokeQuestion:
				'Zustimmung widerrufen? Die KI-Zusammenfassung wird wieder gesperrt; die Suche funktioniert weiter.',
			cancel: 'Abbrechen',
			noscript: 'Die Suche braucht JavaScript.'
		}
	};

	/* ---------------------------------------------------------------- helpers */

	function cn(name) {
		return P + name;
	}

	function el(tag, classes, attrs) {
		var e = document.createElement(tag);
		if (classes) e.className = classes;
		if (attrs)
			Object.keys(attrs).forEach(function (k) {
				e.setAttribute(k, attrs[k]);
			});
		return e;
	}

	function escapeHtml(s) {
		return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
	}

	function resolveLang(raw) {
		if (raw && TEXT[raw]) return raw;
		// The host page's language beats English: a German site with no data-lang
		// should not get an English search button.
		var docLang = (document.documentElement.getAttribute('lang') || '').slice(0, 2);
		if (TEXT[docLang]) return docLang;
		return 'en';
	}

	// Only http(s) is accepted; the value comes from the host page and ends up in an
	// href. A malformed value counts as "no terms configured" rather than locking the
	// overview forever.
	function normalizeTermsUrl(raw) {
		if (!raw) return '';
		try {
			var u = new URL(raw, window.location.href);
			if (u.protocol !== 'http:' && u.protocol !== 'https:') throw new Error('unsupported scheme');
			return u.href;
		} catch (e) {
			if (window.console && window.console.warn) {
				window.console.warn('[edtechrag-search] ignoring invalid data-userterms-url:', raw);
			}
			return '';
		}
	}

	function parseDurationMonths(raw) {
		var months = parseInt(raw, 10);
		if (!isFinite(months)) return USERTERMS_DEFAULT_MONTHS;
		return Math.min(Math.max(months, USERTERMS_MIN_MONTHS), USERTERMS_MAX_MONTHS);
	}

	/*
	 * Minimal Markdown for the overview: paragraphs, links, bold, italic, bullets.
	 *
	 * Deliberately NOT marked.umd.js like the chatbot. The overview is three to six
	 * sentences with citations - a 41 KB parser for that is a load the host page pays
	 * on every search page. Everything is escaped first, so an injected tag cannot
	 * survive: only the patterns below are turned back into markup.
	 */
	function renderOverview(text) {
		var out = escapeHtml(text)
			// [label](https://...) - only http(s), so a javascript: URL cannot get through.
			.replace(/\[([^\]]+)\]\((https?:\/\/[^\s)]+)\)/g, function (m, label, href) {
				return '<a href="' + href + '" target="_blank" rel="noopener noreferrer">' + label + '</a>';
			})
			.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
			.replace(/(^|[\s(])\*([^*\n]+)\*/g, '$1<em>$2</em>');

		var blocks = out.split(/\n{2,}/);
		return blocks
			.map(function (block) {
				var lines = block.split('\n');
				var bullets = lines.filter(function (l) {
					return /^\s*[-*]\s+/.test(l);
				});
				if (bullets.length === lines.length && bullets.length > 0) {
					return (
						'<ul>' +
						lines
							.map(function (l) {
								return '<li>' + l.replace(/^\s*[-*]\s+/, '') + '</li>';
							})
							.join('') +
						'</ul>'
					);
				}
				return '<p>' + lines.join('<br>') + '</p>';
			})
			.join('');
	}

	/* ---------------------------------------------------------------- widget */

	function initWidget(host) {
		var d = host.dataset;
		var embedId = d.embedId || '';
		var baseUrl = d.edtechragBaseUrl || '/edtechrag/';
		if (baseUrl.charAt(baseUrl.length - 1) !== '/') baseUrl += '/';

		var mode = d.mode === 'results' ? 'results' : 'box';
		var queryParam = d.queryParam || 'q';
		var resultsUrl = d.resultsUrl || '';
		var lang = resolveLang(d.lang);
		var T = TEXT[lang];
		var design = d.design || '';
		var limit = parseInt(d.limit, 10);

		// data-ai-overview="off" switches the overview off for this page even when the
		// repository allows it - a page may not be the right place for it.
		var overviewMode = d.aiOverview === 'off' ? 'off' : 'optin';
		var usertermsUrl = normalizeTermsUrl(d.usertermsUrl);
		var usertermsMonths = parseDurationMonths(d.usertermsDuration);

		// Own key, separate from the chatbot's: consenting to a summary is not
		// consenting to a conversation, and withdrawing one must not revoke the other.
		var termsKey = 'edtechrag-search-overview-' + embedId;
		var acceptedAt = null;
		var acceptedUrl = null;

		var overviewAvailable = false;
		var overviewRequiresTerms = true;
		var currentQuery = '';
		var searching = false;

		host.classList.add(cn('host'));
		if (design) host.classList.add(cn('design-' + design));
		host.removeAttribute('hidden');

		/* -- consent state -- */

		function loadAcceptance() {
			try {
				var raw = localStorage.getItem(termsKey);
				if (!raw) return;
				var rec = JSON.parse(raw);
				// JSON.parse happily returns null, numbers and arrays; only trust the
				// expected shape.
				if (!rec || typeof rec !== 'object' || Array.isArray(rec)) return;
				if (typeof rec.acceptedAt !== 'string' || typeof rec.url !== 'string') return;
				acceptedAt = rec.acceptedAt;
				acceptedUrl = rec.url;
			} catch (e) {
				/* storage disabled, private mode or junk */
			}
		}

		function saveAcceptance() {
			try {
				localStorage.setItem(
					termsKey,
					JSON.stringify({ acceptedAt: acceptedAt, url: acceptedUrl, months: usertermsMonths })
				);
			} catch (e) {
				/* storage quota or private mode */
			}
		}

		function clearAcceptance() {
			acceptedAt = null;
			acceptedUrl = null;
			try {
				localStorage.removeItem(termsKey);
			} catch (e) {
				/* */
			}
		}

		function termsValid() {
			if (!overviewRequiresTerms) return true;
			// A changed URL means a new version of the terms, so consent has to be
			// given again.
			if (!acceptedAt || acceptedUrl !== usertermsUrl) return false;
			var parsed = Date.parse(acceptedAt);
			if (!isFinite(parsed)) return false;
			var now = Date.now();
			// A stamp from the future means the clock was wrong; ask again rather than
			// block forever.
			if (parsed > now) return false;
			return now - parsed < usertermsMonths * MONTH_MS;
		}

		function acceptTerms() {
			// In-memory first and independently of persistence: in private mode
			// setItem throws, and the visitor should still get their summary.
			acceptedAt = new Date().toISOString();
			acceptedUrl = usertermsUrl;
			saveAcceptance();
		}

		/* -- markup -- */

		var form = el('form', cn('form'), { role: 'search' });
		var inputId = cn('input-') + (embedId || 'x').replace(/[^A-Za-z0-9_-]/g, '');
		var label = el('label', cn('label'), { for: inputId });
		label.textContent = T.label;
		var input = el('input', cn('input'), {
			id: inputId,
			type: 'search',
			name: queryParam,
			placeholder: d.placeholder || T.placeholder,
			autocomplete: 'off'
		});
		var submit = el('button', cn('submit'), { type: 'submit' });
		submit.textContent = T.submit;

		form.appendChild(label);
		var row = el('div', cn('row'));
		row.appendChild(input);
		row.appendChild(submit);
		form.appendChild(row);
		host.appendChild(form);

		// The box mode is done here: no result area, no live region, no network.
		if (mode === 'box') {
			form.addEventListener('submit', function (event) {
				var value = input.value.trim();
				if (!value) {
					event.preventDefault();
					return;
				}
				if (!resultsUrl) {
					// Without a target there is nothing to navigate to. Say so once
					// instead of swallowing the submit.
					event.preventDefault();
					if (window.console && window.console.warn) {
						window.console.warn('[edtechrag-search] data-results-url is missing');
					}
					return;
				}
				event.preventDefault();
				var target = new URL(resultsUrl, window.location.href);
				target.searchParams.set(queryParam, value);
				window.location.href = target.href;
			});
			return;
		}

		/* -- results mode -- */

		var overviewBox = el('section', cn('overview'), { hidden: 'hidden' });
		var resultsBox = el('div', cn('results'));
		// aria-live so a screen reader hears that results arrived: the list appears
		// without a page load, and nothing else would announce it.
		var status = el('p', cn('status'), { role: 'status', 'aria-live': 'polite' });
		var queriesBox = el('p', cn('queries'), { hidden: 'hidden' });

		host.appendChild(status);
		host.appendChild(overviewBox);
		host.appendChild(queriesBox);
		host.appendChild(resultsBox);

		function setStatus(text) {
			status.textContent = text || '';
		}

		/* -- rendering -- */

		function renderResults(hits) {
			resultsBox.innerHTML = '';
			if (!hits.length) {
				var empty = el('p', cn('empty'));
				empty.textContent = T.noResults;
				resultsBox.appendChild(empty);
				return;
			}

			// <ol> and not a stack of <div>: the order is the ranking, and a screen
			// reader announces "list, 8 items" instead of leaving the visitor to count.
			var list = el('ol', cn('list'));
			hits.forEach(function (hit) {
				var item = el('li', cn('item'));

				var link = el('a', cn('item-title'), { href: hit.url });
				link.textContent = hit.title || hit.url;
				var heading = el('h3', cn('item-heading'));
				heading.appendChild(link);
				item.appendChild(heading);

				var url = el('p', cn('item-url'));
				url.textContent = hit.url;
				item.appendChild(url);

				if (hit.snippet) {
					var snippet = el('p', cn('item-snippet'));
					snippet.textContent = hit.snippet;
					item.appendChild(snippet);
				}

				// Whatever the repository declared as meta tags - type, category,
				// runtime. Rendered as plain text: these are facts, not links.
				var metaKeys = hit.meta ? Object.keys(hit.meta) : [];
				if (metaKeys.length) {
					var meta = el('p', cn('item-meta'));
					meta.textContent = metaKeys
						.map(function (key) {
							return hit.meta[key];
						})
						.join(' \u00b7 ');
					item.appendChild(meta);
				}

				list.appendChild(item);
			});
			resultsBox.appendChild(list);
		}

		function renderQueries(queries) {
			if (!queries || !queries.length) {
				queriesBox.setAttribute('hidden', 'hidden');
				return;
			}
			queriesBox.textContent = T.queriesLabel + ' ' + queries.join(' \u00b7 ');
			queriesBox.removeAttribute('hidden');
		}

		/* -- overview -- */

		function hideOverview() {
			overviewBox.setAttribute('hidden', 'hidden');
			overviewBox.innerHTML = '';
		}

		function overviewHeader() {
			var head = el('div', cn('overview-head'));
			var heading = el('h2', cn('overview-heading'));
			heading.textContent = T.overviewHeading;
			head.appendChild(heading);
			return head;
		}

		/** The consent panel: what happens, a link to the terms, and one button. */
		function showOverviewGate() {
			overviewBox.innerHTML = '';
			overviewBox.appendChild(overviewHeader());

			var intro = el('p', cn('overview-intro'));
			intro.textContent = T.overviewIntro;
			overviewBox.appendChild(intro);

			if (usertermsUrl) {
				var termsLine = el('p', cn('overview-terms'));
				var termsLink = el('a', cn('overview-terms-link'), {
					href: usertermsUrl,
					target: '_blank',
					rel: 'noopener noreferrer'
				});
				termsLink.textContent = T.termsLinkLabel;
				termsLine.appendChild(termsLink);
				overviewBox.appendChild(termsLine);
			}

			var accept = el('button', cn('overview-accept'), { type: 'button' });
			accept.textContent = T.overviewAccept;
			accept.addEventListener('click', function () {
				acceptTerms();
				requestOverview(currentQuery);
			});
			overviewBox.appendChild(accept);

			overviewBox.removeAttribute('hidden');
		}

		/**
		 * The withdraw control. Sits next to the heading of a generated overview, so
		 * it is reachable exactly where the thing it revokes is visible.
		 */
		function appendRevoke(head) {
			if (!overviewRequiresTerms) return;
			var menu = el('button', cn('overview-menu'), {
				type: 'button',
				'aria-label': T.menu,
				title: T.revoke
			});
			menu.textContent = '\u22ef';
			menu.addEventListener('click', function () {
				// A native confirm() and not a custom dialog: it is keyboard operable,
				// announced, and cannot be styled into something unreadable by the host
				// page's CSS.
				if (window.confirm(T.revokeQuestion)) {
					clearAcceptance();
					showOverviewGate();
				}
			});
			head.appendChild(menu);
		}

		function requestOverview(query) {
			if (!query) return;

			overviewBox.innerHTML = '';
			var head = overviewHeader();
			appendRevoke(head);
			overviewBox.appendChild(head);

			var body = el('div', cn('overview-body'), { 'aria-live': 'polite' });
			var pending = el('p', cn('overview-pending'));
			pending.textContent = T.overviewGenerating;
			body.appendChild(pending);
			overviewBox.appendChild(body);
			overviewBox.removeAttribute('hidden');

			var decoder = new TextDecoder();
			var answer = '';

			fetch(baseUrl + 'api/search-overview/' + encodeURIComponent(embedId), {
				method: 'POST',
				headers: { 'Content-Type': 'application/json' },
				body: JSON.stringify({
					query: query,
					source: window.location.href,
					usertermsUrl: usertermsUrl || undefined,
					termsAcceptedAt: acceptedAt || undefined
				})
			})
				.then(function (res) {
					if (res.status === 403) {
						return res.text().then(function (text) {
							if (text && text.indexOf('userterms-required') !== -1) {
								// The server rejected our stored acceptance: ask again instead
								// of showing an error the visitor cannot act on.
								clearAcceptance();
								showOverviewGate();
								return null;
							}
							throw new Error('Request failed (403)');
						});
					}
					// The repository switched the overview off while the page was open.
					if (res.status === 409) {
						hideOverview();
						return null;
					}
					if (!res.ok || !res.body) throw new Error('Request failed (' + res.status + ')');

					var reader = res.body.getReader();
					function read() {
						return reader.read().then(function (chunk) {
							if (chunk.done) {
								var note = el('p', cn('overview-note'));
								note.textContent = T.overviewNote;
								overviewBox.appendChild(note);
								return null;
							}
							answer += decoder.decode(chunk.value || new Uint8Array(), { stream: true });
							body.innerHTML = renderOverview(answer);
							return read();
						});
					}
					return read();
				})
				.catch(function (err) {
					body.innerHTML =
						'<p class="' +
						cn('error') +
						'">' +
						escapeHtml(T.errorPrefix + ' ' + err.message) +
						'</p>';
				});
		}

		/* -- search -- */

		function runSearch(query) {
			if (!query || searching) return;
			searching = true;
			currentQuery = query;

			setStatus(T.searching);
			hideOverview();
			resultsBox.innerHTML = '';
			renderQueries([]);

			var payload = { query: query };
			if (isFinite(limit) && limit > 0) payload.limit = limit;

			fetch(baseUrl + 'api/search/' + encodeURIComponent(embedId), {
				method: 'POST',
				headers: { 'Content-Type': 'application/json' },
				body: JSON.stringify(payload)
			})
				.then(function (res) {
					return res.json().then(function (data) {
						if (!res.ok || data.success === false) {
							throw new Error(data.message || 'Request failed (' + res.status + ')');
						}
						return data;
					});
				})
				.then(function (data) {
					searching = false;
					var hits = data.results || [];
					overviewAvailable = data.overviewAvailable === true && overviewMode !== 'off';
					overviewRequiresTerms = data.overviewRequiresTerms !== false;
					if (typeof data.overviewTermsMonths === 'number') {
						usertermsMonths = parseDurationMonths(data.overviewTermsMonths);
					}

					setStatus(T.resultsFor + ' \u201c' + query + '\u201d \u2013 ' + T.resultCount(hits.length));
					renderQueries(data.queries);
					renderResults(hits);

					// The results are up; only now is the overview offered - and only when
					// there is something to summarise.
					if (overviewAvailable && hits.length > 0) {
						if (termsValid()) requestOverview(query);
						else showOverviewGate();
					}
				})
				.catch(function (err) {
					searching = false;
					setStatus('');
					resultsBox.innerHTML =
						'<p class="' +
						cn('error') +
						'">' +
						escapeHtml(T.errorPrefix + ' ' + err.message) +
						'</p>';
				});
		}

		/* -- init -- */

		loadAcceptance();

		form.addEventListener('submit', function (event) {
			event.preventDefault();
			var value = input.value.trim();
			if (!value) return;
			// Keep the address in step with what is shown, so the result page can be
			// bookmarked and the back button works.
			var target = new URL(window.location.href);
			target.searchParams.set(queryParam, value);
			if (window.history && window.history.pushState) {
				window.history.pushState({}, '', target.href);
			}
			runSearch(value);
		});

		window.addEventListener('popstate', function () {
			var q = new URL(window.location.href).searchParams.get(queryParam) || '';
			input.value = q;
			if (q) runSearch(q);
			else {
				resultsBox.innerHTML = '';
				hideOverview();
				setStatus('');
			}
		});

		var initial = new URL(window.location.href).searchParams.get(queryParam) || '';
		if (initial) {
			input.value = initial;
			runSearch(initial);
		}
	}

	function initAll() {
		var hosts = document.querySelectorAll('.at-ed-tech-edtechrag-search');
		if (!hosts.length) return;
		Array.prototype.forEach.call(hosts, function (host) {
			/*
			 * Ein Einbaupunkt wird genau einmal eingerichtet.
			 *
			 * Der Grund ist nicht theoretisch: eine Seite mit Box im Kopf UND
			 * Ergebnisliste im Rumpf bindet dieses Script ueber zwei Komponenten ein,
			 * und der Browser fuehrt dasselbe <script src> zweimal aus. Ohne diese
			 * Marke haette dann jeder Einbaupunkt zwei Formulare und zwei
			 * Absende-Handler - also zwei Suchanfragen pro Klick.
			 */
			if (host.getAttribute('data-edtechrag-ready') === '1') return;
			host.setAttribute('data-edtechrag-ready', '1');
			initWidget(host);
		});
	}

	if (document.readyState === 'loading') {
		document.addEventListener('DOMContentLoaded', initAll);
	} else {
		initAll();
	}
})();
