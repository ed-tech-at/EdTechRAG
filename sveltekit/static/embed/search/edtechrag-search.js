/*
 * EdTechRAG search embed - a search box and a result page for any website.
 *
 * This file must stay ASCII-only: static .js is served without a charset, so a
 * classic <script src> inherits the encoding of the host page. Write non-ASCII
 * text as \uXXXX escapes.
 * Check with: LC_ALL=C grep -n '[^ -~\t]' edtechrag-search.js   (must print nothing)
 *
 * Two modes on one script, chosen with data-mode:
 *
 *   box      an input plus a button. Submitting navigates to data-results-url
 *            with ?q=... - the same thing a search field in a header does.
 *   results  reads ?q= from the address, shows the input, the result list, and
 *            above it the optional AI overview.
 *
 * The results appear WITHOUT consent; the AI overview only after it. That split is
 * the point of the feature and the reason there are two endpoints behind it.
 *
 * The overview is a switch: one button enables it, and while it is enabled a
 * second button disables it again - always visible, also while a search or a
 * summary is still running. Consent is stored with day precision only.
 */
(function () {
	'use strict';

	var P = 'at-ed-tech-edtechrag-src-';

	/* -- Consent, mirroring block_chatbot/edtechrag.js -- */
	var USERTERMS_DEFAULT_MONTHS = 12;
	var USERTERMS_MIN_MONTHS = 1;
	var USERTERMS_MAX_MONTHS = 60;
	// Fixed 30-day months, matching src/lib/ragContext.ts. Calendar math is
	// timezone/DST dependent and would make client and server disagree at the
	// expiry boundary.
	var MONTH_MS = 30 * 24 * 60 * 60 * 1000;

	var TEXT = {
		en: {
			label: 'Search',
			placeholder: 'Search ...',
			submit: 'Search',
			searching: 'Searching ...',
			resultsFor: 'Results for',
			noResults: 'Nothing found. Try other words.',
			// The same situation while the overview is still on the table. It searches
			// by meaning, so it routinely finds pages the full text missed - saying
			// "nothing found" at that moment would be a verdict on half the job.
			noResultsPending:
				'No literal match. The AI overview searches by meaning rather than spelling and may still find something.',
			resultCount: function (n) {
				return n === 1 ? '1 result' : n + ' results';
			},
			queriesLabel: 'Search terms:',
			errorPrefix: 'Error:',
			overviewHeading: 'AI overview',
			overviewEnable: 'Enable AI overview',
			overviewDisable: 'Disable AI overview',
			overviewGenerating: 'Writing AI overview ...',
			overviewNote: 'Generated by a language model - please check against the sources.',
			ragHeading: 'Best matches for your question',
			dbHeading: 'Further pages containing your words',
			termsLinkLabel: 'Terms of use',
			noscript: 'The search needs JavaScript.'
		},
		de: {
			label: 'Suche',
			placeholder: 'Suchen ...',
			submit: 'Suchen',
			searching: 'Suche l\u00e4uft ...',
			resultsFor: 'Ergebnisse f\u00fcr',
			noResults: 'Nichts gefunden. Versuchen Sie es mit anderen Worten.',
			noResultsPending:
				'Kein Treffer im Wortlaut. Die AI-Zusammenfassung sucht nach Bedeutung statt nach Buchstaben und kann trotzdem etwas finden.',
			resultCount: function (n) {
				return n === 1 ? '1 Ergebnis' : n + ' Ergebnisse';
			},
			queriesLabel: 'Suchbegriffe:',
			errorPrefix: 'Fehler:',
			overviewHeading: 'AI-Zusammenfassung',
			overviewEnable: 'AI-Zusammenfassung aktivieren',
			overviewDisable: 'AI-Zusammenfassung deaktivieren',
			overviewGenerating: 'Zusammenfassung wird geschrieben ...',
			overviewNote:
				'Von einem Sprachmodell erzeugt - bitte an den Quellen gegenpr\u00fcfen.',
			ragHeading: 'Beste Treffer zu Ihrer Frage',
			dbHeading: 'Weitere Seiten mit Ihren Suchbegriffen',
			termsLinkLabel: 'Nutzungsbedingungen',
			noscript: 'Die Suche braucht JavaScript.'
		}
	};

	/* ---------------------------------------------------------------- helpers */

	function cn(name) {
		return P + name;
	}

	function el(tag, classes, attrs) {
		var e = document.createElement(tag);
		if (classes) e.className = classes;
		if (attrs)
			Object.keys(attrs).forEach(function (k) {
				e.setAttribute(k, attrs[k]);
			});
		return e;
	}

	function escapeHtml(s) {
		return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
	}

	/*
	 * Own properties only.
	 *
	 * A document meta key may be called `constructor` or `toString` - the ingest side
	 * stores whatever the source wrote - and a plain `table[key]` would then answer
	 * with a function off Object.prototype, which would be rendered as the label.
	 */
	function ownString(table, key) {
		return Object.prototype.hasOwnProperty.call(table, key) && typeof table[key] === 'string'
			? table[key]
			: '';
	}

	function resolveLang(raw) {
		if (raw && TEXT[raw]) return raw;
		// The host page's language beats English: a German site with no data-lang
		// should not get an English search button.
		var docLang = (document.documentElement.getAttribute('lang') || '').slice(0, 2);
		if (TEXT[docLang]) return docLang;
		return 'en';
	}

	// Only http(s) is accepted; the value comes from the host page and ends up in an
	// href. A malformed value counts as "no terms configured" rather than locking the
	// overview forever.
	function normalizeTermsUrl(raw) {
		if (!raw) return '';
		try {
			var u = new URL(raw, window.location.href);
			if (u.protocol !== 'http:' && u.protocol !== 'https:') throw new Error('unsupported scheme');
			return u.href;
		} catch (e) {
			if (window.console && window.console.warn) {
				window.console.warn('[edtechrag-search] ignoring invalid data-userterms-url:', raw);
			}
			return '';
		}
	}

	function parseDurationMonths(raw) {
		var months = parseInt(raw, 10);
		if (!isFinite(months)) return USERTERMS_DEFAULT_MONTHS;
		return Math.min(Math.max(months, USERTERMS_MIN_MONTHS), USERTERMS_MAX_MONTHS);
	}

	/*
	 * Minimal Markdown for the overview: paragraphs, links, bold, italic, bullets.
	 *
	 * Deliberately NOT marked.umd.js like the chatbot. The overview is three to six
	 * sentences with citations - a 41 KB parser for that is a load the host page pays
	 * on every search page. Everything is escaped first, so an injected tag cannot
	 * survive: only the patterns below are turned back into markup.
	 */
	function renderOverview(text) {
		var out = escapeHtml(text)
			/*
			 * [label](https://...) AND a bare https://... - in ONE pass.
			 *
			 * Only http(s), so a javascript: URL cannot get through, and no quote in
			 * the address, so it cannot leave the href it is written into.
			 *
			 * The bare form is a safety net, not an invitation: the prompt asks for
			 * Markdown links (see src/lib/server/searchPrompt.ts), but a model drops
			 * the syntax now and then, and an address in the middle of a sentence
			 * should be reachable rather than punish the visitor for it.
			 *
			 * One alternation and not two passes: a second pass would find the URLs
			 * the first one had just written into href="..." and wrap them again.
			 */
			.replace(
				/\[([^\]]+)\]\((https?:\/\/[^\s)"]+)\)|(https?:\/\/[^\s<"]+)/g,
				function (m, label, href, bare) {
					if (href) {
						return (
							'<a href="' + href + '" target="_blank" rel="noopener noreferrer">' + label + '</a>'
						);
					}
					// Satzzeichen am Ende gehoeren zum Satz und nicht zur Adresse - ohne
					// diese Zeile endet jeder Link am Satzende auf einem Punkt.
					var url = bare.replace(/[.,;:!?)\]]+$/, '');
					var tail = bare.slice(url.length);
					return (
						'<a href="' + url + '" target="_blank" rel="noopener noreferrer">' + url + '</a>' + tail
					);
				}
			)
			.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
			.replace(/(^|[\s(])\*([^*\n]+)\*/g, '$1<em>$2</em>');

		var blocks = out.split(/\n{2,}/);
		return blocks
			.map(function (block) {
				var lines = block.split('\n');
				var bullets = lines.filter(function (l) {
					return /^\s*[-*]\s+/.test(l);
				});
				if (bullets.length === lines.length && bullets.length > 0) {
					return (
						'<ul>' +
						lines
							.map(function (l) {
								return '<li>' + l.replace(/^\s*[-*]\s+/, '') + '</li>';
							})
							.join('') +
						'</ul>'
					);
				}
				return '<p>' + lines.join('<br>') + '</p>';
			})
			.join('');
	}

	/* ---------------------------------------------------------------- widget */

	function initWidget(host) {
		var d = host.dataset;
		var embedId = d.embedId || '';
		var baseUrl = d.edtechragBaseUrl || '/edtechrag/';
		if (baseUrl.charAt(baseUrl.length - 1) !== '/') baseUrl += '/';

		var mode = d.mode === 'results' ? 'results' : 'box';
		var queryParam = d.queryParam || 'q';
		var resultsUrl = d.resultsUrl || '';
		var lang = resolveLang(d.lang);
		var T = TEXT[lang];
		var design = d.design || '';
		var limit = parseInt(d.limit, 10);

		// data-ai-overview="off" switches the overview off for this page even when the
		// repository allows it - a page may not be the right place for it.
		var overviewMode = d.aiOverview === 'off' ? 'off' : 'optin';
		var usertermsUrl = normalizeTermsUrl(d.usertermsUrl);
		var usertermsMonths = parseDurationMonths(d.usertermsDuration);

		// Own key, separate from the chatbot's: consenting to a summary is not
		// consenting to a conversation, and withdrawing one must not revoke the other.
		var termsKey = 'edtechrag-search-overview-' + embedId;
		var acceptedAt = null;
		var acceptedUrl = null;

		// null until the first search answered: the disable switch shows on stored
		// consent already while that search runs, and hides once the repository says
		// the overview is off.
		var overviewAvailable = null;
		var overviewRequiresTerms = true;
		/*
		 * Steht das Angebot der Zusammenfassung gerade? Entweder wartet sie auf die
		 * Zustimmung, oder sie wird gerade geschrieben.
		 *
		 * Die Marke gehoert der Trefferliste, nicht dem Kasten: solange die
		 * Zusammenfassung noch etwas beitragen kann, darf unter einer leeren Liste
		 * nicht "Nichts gefunden" stehen. Sie holt ihre Quellen selbst und ueber die
		 * BEDEUTUNG - der haeufigste Fall einer leeren Volltextsuche ist ein
		 * Tippfehler, und genau den uebersteht die semantische Suche.
		 *
		 * Wer das Angebot zeigt, setzt sie; wer es wegnimmt, loescht sie.
		 */
		var overviewPending = false;
		// AbortController of the summary that is streaming right now, if any.
		var overviewController = null;
		var currentQuery = '';
		var searching = false;
		// Getrennt gehalten: die Datenbanktreffer stehen sofort da, die semantischen
		// kommen erst mit dem Overview - also nach der Zustimmung. Ein gemeinsames
		// Array muesste beim Widerruf wieder auseinandersortiert werden.
		var dbHits = [];
		var ragHits = [];
		/*
		 * Naming table for the meta line: key -> display name, already resolved to
		 * this widget's language by the server (see /api/search).
		 *
		 * Lives next to the hits and is replaced with them: a table from a previous
		 * search must not outlive its result list.
		 */
		var metaLabels = {};

		var SOURCES_START = '__EDTECH_SOURCES_START__\n';
		var SOURCES_END = '\n__EDTECH_SOURCES_END__\n';

		host.classList.add(cn('host'));
		if (design) host.classList.add(cn('design-' + design));
		host.removeAttribute('hidden');

		/* -- consent state -- */

		function loadAcceptance() {
			try {
				var raw = localStorage.getItem(termsKey);
				if (!raw) return;
				var rec = JSON.parse(raw);
				// JSON.parse happily returns null, numbers and arrays; only trust the
				// expected shape.
				if (!rec || typeof rec !== 'object' || Array.isArray(rec)) return;
				if (typeof rec.acceptedAt !== 'string' || typeof rec.url !== 'string') return;
				// Older versions stored the full ISO time. Keep the consent, drop the time.
				acceptedAt = rec.acceptedAt.slice(0, 10);
				acceptedUrl = rec.url;
				if (acceptedAt !== rec.acceptedAt) saveAcceptance();
			} catch (e) {
				/* storage disabled, private mode or junk */
			}
		}

		function saveAcceptance() {
			try {
				localStorage.setItem(
					termsKey,
					JSON.stringify({ acceptedAt: acceptedAt, url: acceptedUrl, months: usertermsMonths })
				);
			} catch (e) {
				/* storage quota or private mode */
			}
		}

		function clearAcceptance() {
			acceptedAt = null;
			acceptedUrl = null;
			try {
				localStorage.removeItem(termsKey);
			} catch (e) {
				/* */
			}
		}

		function termsValid() {
			if (!overviewRequiresTerms) return true;
			// A changed URL means a new version of the terms, so consent has to be
			// given again.
			if (!acceptedAt || acceptedUrl !== usertermsUrl) return false;
			var parsed = Date.parse(acceptedAt);
			if (!isFinite(parsed)) return false;
			var now = Date.now();
			// A stamp from the future means the clock was wrong; ask again rather than
			// block forever.
			if (parsed > now) return false;
			return now - parsed < usertermsMonths * MONTH_MS;
		}

		function acceptTerms() {
			// In-memory first and independently of persistence: in private mode
			// setItem throws, and the visitor should still get their summary.
			//
			// The day only (YYYY-MM-DD, UTC), not the time: the date is all the expiry
			// needs, and it is sent along and logged. UTC like the server, so the stamp
			// can never lie in its future.
			acceptedAt = new Date().toISOString().slice(0, 10);
			acceptedUrl = usertermsUrl;
			saveAcceptance();
		}

		/* -- markup -- */

		var form = el('form', cn('form'), { role: 'search' });
		var inputId = cn('input-') + (embedId || 'x').replace(/[^A-Za-z0-9_-]/g, '');
		var label = el('label', cn('label'), { for: inputId });
		label.textContent = T.label;
		var input = el('input', cn('input'), {
			id: inputId,
			type: 'search',
			name: queryParam,
			placeholder: d.placeholder || T.placeholder,
			autocomplete: 'off'
		});
		var submit = el('button', cn('submit'), { type: 'submit' });
		submit.textContent = T.submit;

		form.appendChild(label);
		var row = el('div', cn('row'));
		row.appendChild(input);
		row.appendChild(submit);
		form.appendChild(row);
		host.appendChild(form);

		// The box mode is done here: no result area, no live region, no network.
		if (mode === 'box') {
			form.addEventListener('submit', function (event) {
				var value = input.value.trim();
				if (!value) {
					event.preventDefault();
					return;
				}
				if (!resultsUrl) {
					// Without a target there is nothing to navigate to. Say so once
					// instead of swallowing the submit.
					event.preventDefault();
					if (window.console && window.console.warn) {
						window.console.warn('[edtechrag-search] data-results-url is missing');
					}
					return;
				}
				event.preventDefault();
				var target = new URL(resultsUrl, window.location.href);
				target.searchParams.set(queryParam, value);
				window.location.href = target.href;
			});
			return;
		}

		/* -- results mode -- */

		var overviewBox = el('section', cn('overview'), { hidden: 'hidden' });
		var resultsBox = el('div', cn('results'));
		// aria-live so a screen reader hears that results arrived: the list appears
		// without a page load, and nothing else would announce it.
		var status = el('p', cn('status'), { role: 'status', 'aria-live': 'polite' });
		var queriesBox = el('p', cn('queries'), { hidden: 'hidden' });

		/*
		 * The disable switch. ONE element for the widget's lifetime, moved into the
		 * footer of the overview box each time the box is built - the box is emptied
		 * on every search, the button is not rebuilt with it, so focus handling and
		 * the listener stay in one place.
		 *
		 * The footer is built together with the box, not when the summary is done: the
		 * switch has to be there while the search is still running and while the
		 * summary is being written.
		 *
		 * No confirmation dialog: disabling destroys nothing the visitor cannot get
		 * back with one click on "enable".
		 */
		var disableBtn = el('button', cn('overview-toggle'), { type: 'button' });
		disableBtn.textContent = T.overviewDisable;

		host.appendChild(status);
		host.appendChild(overviewBox);
		host.appendChild(queriesBox);
		host.appendChild(resultsBox);

		disableBtn.addEventListener('click', function () {
			abortOverview();
			clearAcceptance();
			// Die semantischen Treffer kamen mit der Zustimmung, sie gehen mit ihr.
			ragHits = [];
			// Erst das Angebot, dann die Liste - siehe runSearch: bleibt danach nichts
			// uebrig, haengt der Text der leeren Liste daran, dass die Zusammenfassung
			// wieder aktiviert werden kann.
			if (overviewAvailable && currentQuery && !searching) {
				showOverviewGate();
				// Der Knopf, der den Fokus hatte, ist weg; der Fokus geht auf sein
				// Gegenstueck statt ins Leere.
				var enable = overviewBox.querySelector('.' + cn('overview-enable'));
				if (enable) enable.focus();
			} else {
				hideOverview();
			}
			if (currentQuery && !searching) renderResults();
		});

		function setStatus(text) {
			status.textContent = text || '';
		}

		/* -- rendering -- */

		/**
		 * The whole result area: the semantic hits of the AI overview first, then the
		 * database hits.
		 *
		 * That order is the point of the grouping - the RAG matches answer the question,
		 * the full-text matches merely contain the words. A page that appears in both is
		 * shown ONCE, in the upper group: the same title twice would read as two
		 * different pages.
		 *
		 * The semantic group exists only after consent, because that is when its
		 * retrieval happens (see /api/search-overview).
		 */
		function metaLabel(key) {
			return ownString(metaLabels, key);
		}

		function renderResults() {
			resultsBox.innerHTML = '';

			var seen = {};
			var rag = ragHits.filter(function (hit) {
				if (seen[hit.url]) return false;
				seen[hit.url] = true;
				return true;
			});
			var db = dbHits.filter(function (hit) {
				if (seen[hit.url]) return false;
				seen[hit.url] = true;
				return true;
			});

			if (!rag.length && !db.length) {
				var empty = el('p', cn('empty'));
				empty.textContent = overviewPending ? T.noResultsPending : T.noResults;
				resultsBox.appendChild(empty);
				return;
			}

			// Headings only when BOTH groups are there. With one group they would label
			// something that has no counterpart - and a heading that distinguishes
			// nothing is noise.
			var grouped = rag.length > 0 && db.length > 0;
			if (rag.length) appendGroup(grouped ? T.ragHeading : '', rag);
			if (db.length) appendGroup(grouped ? T.dbHeading : '', db);
		}

		function appendGroup(heading, hits) {
			if (heading) {
				var h = el('h2', cn('group-heading'));
				h.textContent = heading;
				resultsBox.appendChild(h);
			}

			// <ol> and not a stack of <div>: the order is the ranking, and a screen
			// reader announces "list, 8 items" instead of leaving the visitor to count.
			var list = el('ol', cn('list'));
			hits.forEach(function (hit) {
				var item = el('li', cn('item'));

				var link = el('a', cn('item-title'), { href: hit.url });
				link.textContent = hit.title || hit.url;
				// itemHeading und nicht heading: `var` ist funktionsweit, der Name wuerde
				// den Parameter der Gruppe ueberschreiben.
				var itemHeading = el('h3', cn('item-heading'));
				itemHeading.appendChild(link);
				item.appendChild(itemHeading);

				var url = el('p', cn('item-url'));
				url.textContent = hit.url;
				item.appendChild(url);

				if (hit.snippet) {
					var snippet = el('p', cn('item-snippet'));
					snippet.textContent = hit.snippet;
					item.appendChild(snippet);
				}

				// Whatever the repository declared as search meta tags - type, category,
				// runtime. Rendered as plain text: these are facts, not links.
				//
				// A key with an entry in the naming table is prefixed with it, so
				// "episode" reads as "Podcast Episode: 42" instead of a bare "42". A key
				// without one keeps showing just its value, which is what the line did
				// before the table existed.
				var metaKeys = hit.meta ? Object.keys(hit.meta) : [];
				if (metaKeys.length) {
					var meta = el('p', cn('item-meta'));
					meta.textContent = metaKeys
						.map(function (key) {
							var label = metaLabel(key);
							return label ? label + ': ' + hit.meta[key] : hit.meta[key];
						})
						.join(' \u00b7 ');
					item.appendChild(meta);
				}

				list.appendChild(item);
			});
			resultsBox.appendChild(list);
		}

		/*
		 * The searched terms - only when they say something the input did not. The
		 * full-text search merely splits the input into words; echoing those back
		 * under the box looked like the query had been rewritten, which it was not.
		 */
		function renderQueries(queries, query) {
			// Whitespace and ASCII punctuation are separators to the server
			// (textSearch.ts), so they do not count as a difference here either.
			function squash(s) {
				return String(s || '')
					.toLowerCase()
					.replace(/[\s!-\/:-@[-^`{-~]+/g, '');
			}
			if (!queries || !queries.length || squash(queries.join(' ')) === squash(query)) {
				queriesBox.setAttribute('hidden', 'hidden');
				return;
			}
			queriesBox.textContent = T.queriesLabel + ' ' + queries.join(' \u00b7 ');
			queriesBox.removeAttribute('hidden');
		}

		/* -- overview -- */

		function hideOverview() {
			abortOverview();
			overviewPending = false;
			overviewBox.classList.remove(cn('overview-gate'));
			overviewBox.setAttribute('hidden', 'hidden');
			overviewBox.innerHTML = '';
		}

		/*
		 * Das Angebot ist vom Tisch - fertig geschrieben, fehlgeschlagen oder vom
		 * Repository abgeschaltet. Blieb die Liste dabei leer, trug sie bis hierher
		 * den Hinweis, dass die Zusammenfassung noch sucht; jetzt ist es endgueltig
		 * ein "nichts gefunden" und muss auch so dastehen.
		 */
		function overviewSettled() {
			if (!overviewPending) return;
			overviewPending = false;
			if (!ragHits.length && !dbHits.length) renderResults();
		}

		function overviewHeader() {
			var head = el('div', cn('overview-head'));
			var heading = el('h2', cn('overview-heading'));
			heading.textContent = T.overviewHeading;
			head.appendChild(heading);
			return head;
		}

		function termsLinkEl() {
			var termsLink = el('a', cn('overview-terms-link'), {
				href: usertermsUrl,
				target: '_blank',
				rel: 'noopener noreferrer'
			});
			termsLink.textContent = T.termsLinkLabel;
			return termsLink;
		}

		/*
		 * The offer: ONE button that enables the summary, and next to it the terms it
		 * is enabled under. No panel, no intro text - what happens with the query is in
		 * the privacy notice of the page and in the terms; the button says what it does.
		 */
		function showOverviewGate() {
			abortOverview();
			overviewPending = true;
			overviewBox.innerHTML = '';
			overviewBox.classList.add(cn('overview-gate'));

			var enable = el('button', cn('overview-enable'), { type: 'button' });
			enable.textContent = T.overviewEnable;
			enable.addEventListener('click', function () {
				acceptTerms();
				requestOverview(currentQuery);
				// Der Knopf ist weg; der Fokus geht auf sein Gegenstueck.
				disableBtn.focus();
			});
			overviewBox.appendChild(enable);

			if (usertermsUrl) {
				var terms = el('span', cn('overview-terms'));
				terms.appendChild(termsLinkEl());
				overviewBox.appendChild(terms);
			}

			overviewBox.removeAttribute('hidden');
		}

		/**
		 * The box of an enabled overview: heading, body, and at the bottom one line
		 * with the disable switch, the note that a model writes this, and the link to
		 * the terms (only when the page configured one). Returns the body.
		 *
		 * Built right away - while searching and while writing - so the switch is
		 * always where it will be once the summary is finished.
		 */
		function showOverviewShell() {
			overviewPending = true;
			overviewBox.innerHTML = '';
			overviewBox.classList.remove(cn('overview-gate'));
			overviewBox.appendChild(overviewHeader());

			var body = el('div', cn('overview-body'), { 'aria-live': 'polite' });
			var pending = el('p', cn('overview-pending'));
			pending.textContent = T.overviewGenerating;
			body.appendChild(pending);
			overviewBox.appendChild(body);

			var footer = el('p', cn('overview-note'));
			if (overviewRequiresTerms) {
				footer.appendChild(disableBtn);
				footer.appendChild(document.createTextNode(' '));
			}
			var note = el('span', cn('overview-note-text'));
			note.textContent = T.overviewNote;
			footer.appendChild(note);
			if (usertermsUrl) {
				footer.appendChild(document.createTextNode(' \u00b7 '));
				footer.appendChild(termsLinkEl());
			}
			overviewBox.appendChild(footer);

			overviewBox.removeAttribute('hidden');
			return body;
		}

		/*
		 * Stops a summary that is still streaming: on disable, on a new search, and
		 * before the offer is shown again. Without it a late chunk would write text
		 * into a box that already shows something else.
		 */
		function abortOverview() {
			if (!overviewController) return;
			overviewController.abort();
			overviewController = null;
		}

		function requestOverview(query) {
			if (!query) return;

			abortOverview();
			var controller = typeof AbortController === 'function' ? new AbortController() : null;
			overviewController = controller;
			// Disabled or replaced while this request was still running: from then on
			// nothing of it may touch the box or the list.
			function stale() {
				return overviewController !== controller || (controller && controller.signal.aborted);
			}

			// The focused switch is moved into the new box; keep the focus on it.
			var hadFocus = document.activeElement === disableBtn;
			var body = showOverviewShell();
			if (hadFocus) disableBtn.focus();

			var decoder = new TextDecoder();
			var answer = '';

			fetch(baseUrl + 'api/search-overview/' + encodeURIComponent(embedId), {
				method: 'POST',
				headers: { 'Content-Type': 'application/json' },
				body: JSON.stringify({
					query: query,
					lang: lang,
					source: window.location.href,
					usertermsUrl: usertermsUrl || undefined,
					termsAcceptedAt: acceptedAt || undefined
				}),
				signal: controller ? controller.signal : undefined
			})
				.then(function (res) {
					if (stale()) return null;
					if (res.status === 403) {
						return res.text().then(function (text) {
							if (text && text.indexOf('userterms-required') !== -1) {
								// The server rejected our stored acceptance: ask again instead
								// of showing an error the visitor cannot act on.
								if (stale()) return null;
								clearAcceptance();
								showOverviewGate();
								return null;
							}
							throw new Error('Request failed (403)');
						});
					}
					// The repository switched the overview off while the page was open.
					if (res.status === 409) {
						overviewSettled();
						hideOverview();
						return null;
					}
					if (!res.ok || !res.body) throw new Error('Request failed (' + res.status + ')');

					var reader = res.body.getReader();
					var buffer = '';
					var sourcesDone = false;

					/**
					 * Peels the source block off the front of the stream.
					 *
					 * Returns true while it is still waiting for the closing delimiter - the
					 * bytes must NOT be treated as summary text before that, or the JSON
					 * would flash up in the panel.
					 */
					function takeSources() {
						if (sourcesDone) return false;
						if (buffer.indexOf(SOURCES_START) !== 0) {
							// No block at all (older server): nothing to wait for.
							if (buffer.length >= SOURCES_START.length) sourcesDone = true;
							return !sourcesDone;
						}
						var end = buffer.indexOf(SOURCES_END);
						if (end === -1) return true;

						var json = buffer.slice(SOURCES_START.length, end);
						buffer = buffer.slice(end + SOURCES_END.length);
						sourcesDone = true;
						try {
							var parsed = JSON.parse(json);
							if (Array.isArray(parsed)) {
								ragHits = parsed;
								renderResults();
							}
						} catch (e) {
							/* A broken block costs the grouping, not the summary. */
						}
						return false;
					}

					function read() {
						return reader.read().then(function (chunk) {
							if (stale()) return null;
							if (chunk.done) {
								overviewController = null;
								overviewSettled();
								return null;
							}
							buffer += decoder.decode(chunk.value || new Uint8Array(), { stream: true });
							if (takeSources()) return read();
							if (buffer) {
								answer += buffer;
								buffer = '';
							}
							body.innerHTML = renderOverview(answer);
							return read();
						});
					}
					return read();
				})
				.catch(function (err) {
					// An abort is the visitor's own doing (disable, new search), not an error.
					if (stale() || (err && err.name === 'AbortError')) return;
					overviewController = null;
					overviewSettled();
					body.innerHTML =
						'<p class="' +
						cn('error') +
						'">' +
						escapeHtml(T.errorPrefix + ' ' + err.message) +
						'</p>';
				});
		}

		/* -- search -- */

		function runSearch(query) {
			if (!query || searching) return;
			searching = true;
			currentQuery = query;

			setStatus(T.searching);
			// Stops a summary of the previous query that is still streaming.
			hideOverview();
			// Enabled: the box with its disable switch stands while the search runs.
			// Whether the repository offers the overview at all is only known from the
			// last answer; before the first one, stored consent is enough.
			if (
				overviewMode !== 'off' &&
				overviewAvailable !== false &&
				overviewRequiresTerms &&
				termsValid()
			) {
				showOverviewShell();
			}
			resultsBox.innerHTML = '';
			renderQueries([]);

			// lang mitsenden: der Index enthaelt beide Sprachfassungen - jede ist ein
			// eigener Text mit eigener Adresse -, aber eine deutsche Suche soll nicht die
			// englische Uebersetzung derselben Seite als zweiten Treffer listen.
			var payload = { query: query, lang: lang };
			if (isFinite(limit) && limit > 0) payload.limit = limit;

			fetch(baseUrl + 'api/search/' + encodeURIComponent(embedId), {
				method: 'POST',
				headers: { 'Content-Type': 'application/json' },
				body: JSON.stringify(payload)
			})
				.then(function (res) {
					return res.json().then(function (data) {
						if (!res.ok || data.success === false) {
							throw new Error(data.message || 'Request failed (' + res.status + ')');
						}
						return data;
					});
				})
				.then(function (data) {
					searching = false;
					var hits = data.results || [];
					overviewAvailable = data.overviewAvailable === true && overviewMode !== 'off';
					overviewRequiresTerms = data.overviewRequiresTerms !== false;
					if (typeof data.overviewTermsMonths === 'number') {
						usertermsMonths = parseDurationMonths(data.overviewTermsMonths);
					}

					dbHits = hits;
					ragHits = [];
					// An older server does not send the field at all; an empty table is the
					// same thing as "no labels configured", so there is nothing to report.
					metaLabels =
						data.metaLabels && typeof data.metaLabels === 'object' ? data.metaLabels : {};
					setStatus(T.resultsFor + ' \u201c' + query + '\u201d \u2013 ' + T.resultCount(hits.length));
					renderQueries(data.queries, query);

					/*
					 * Das Angebot der Zusammenfassung kommt VOR der Liste. Nicht weil es
					 * wichtiger waere - die Liste muss wissen, ob es steht: ohne
					 * Volltexttreffer haengt ihr Text daran (overviewPending).
					 *
					 * Angeboten wird es AUCH bei null Treffern, und das war vorher anders
					 * ("nur wenn es etwas zusammenzufassen gibt"). Die Annahme dahinter
					 * stimmt nicht: die Zusammenfassung fasst nicht diese Liste zusammen,
					 * sie holt ihre Quellen selbst und ueber die Bedeutung. Ein Tippfehler
					 * ist der haeufigste Grund fuer eine leere Volltextsuche, und genau
					 * den uebersteht die semantische Suche - "prompt engineeering" fand im
					 * Wortlaut nichts und bekam bis hierher nicht einmal den Knopf
					 * angeboten, mit dem die Seiten zu Prompt Engineering zu holen waren.
					 */
					if (overviewAvailable) {
						if (termsValid()) requestOverview(query);
						else showOverviewGate();
					} else {
						// The box shown while searching, for an overview that is switched off.
						hideOverview();
					}
					renderResults();
				})
				.catch(function (err) {
					searching = false;
					metaLabels = {};
					hideOverview();
					setStatus('');
					resultsBox.innerHTML =
						'<p class="' +
						cn('error') +
						'">' +
						escapeHtml(T.errorPrefix + ' ' + err.message) +
						'</p>';
				});
		}

		/* -- init -- */

		loadAcceptance();

		form.addEventListener('submit', function (event) {
			event.preventDefault();
			var value = input.value.trim();
			if (!value) return;
			// Keep the address in step with what is shown, so the result page can be
			// bookmarked and the back button works.
			var target = new URL(window.location.href);
			target.searchParams.set(queryParam, value);
			if (window.history && window.history.pushState) {
				window.history.pushState({}, '', target.href);
			}
			runSearch(value);
		});

		window.addEventListener('popstate', function () {
			var q = new URL(window.location.href).searchParams.get(queryParam) || '';
			input.value = q;
			if (q) runSearch(q);
			else {
				resultsBox.innerHTML = '';
				hideOverview();
				setStatus('');
			}
		});

		var initial = new URL(window.location.href).searchParams.get(queryParam) || '';
		if (initial) {
			input.value = initial;
			runSearch(initial);
		}
	}

	function initAll() {
		var hosts = document.querySelectorAll('.at-ed-tech-edtechrag-search');
		if (!hosts.length) return;
		Array.prototype.forEach.call(hosts, function (host) {
			/*
			 * Ein Einbaupunkt wird genau einmal eingerichtet.
			 *
			 * Der Grund ist nicht theoretisch: eine Seite mit Box im Kopf UND
			 * Ergebnisliste im Rumpf bindet dieses Script ueber zwei Komponenten ein,
			 * und der Browser fuehrt dasselbe <script src> zweimal aus. Ohne diese
			 * Marke haette dann jeder Einbaupunkt zwei Formulare und zwei
			 * Absende-Handler - also zwei Suchanfragen pro Klick.
			 */
			if (host.getAttribute('data-edtechrag-ready') === '1') return;
			host.setAttribute('data-edtechrag-ready', '1');
			initWidget(host);
		});
	}

	if (document.readyState === 'loading') {
		document.addEventListener('DOMContentLoaded', initAll);
	} else {
		initAll();
	}
})();
